export function getScoreTier(score) {
  if (score >= 78) return { grade: 'A', label: "Walker's Haven", color: '#1F7A4C' };
  if (score >= 70) return { grade: 'B+', label: 'Very Walkable', color: '#0E7C7B' };
  if (score >= 60) return { grade: 'B', label: 'Somewhat Walkable', color: '#D96B27' };
  return { grade: 'C', label: 'Car-Dependent', color: '#B91C1C' };
}
